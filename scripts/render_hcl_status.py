"""Render the four short current-plan indexes from the single manifest."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def render(manifest):
    current = manifest['current_execution']
    links = ('完整规格：[HCL_SYSTEM_REDESIGN_SPEC.md](docs/HCL_SYSTEM_REDESIGN_SPEC.md)；'
             '唯一结构化计划：[hcl_design_manifest.json](docs/hcl_design_manifest.json)；'
             '执行交接：[HCL_CODEX_HANDOFF.md](docs/HCL_CODEX_HANDOFF.md)。')
    status = (f"当前切片：**{current['delivered_slice']} / {current['readiness']}**。"
              f"{current['scope']}\n\n{current['validation']}\n\n"
              f"**NEXT_READY：{current['next_slice']}**。{current['remaining']}\n")
    if current.get("active_work"):
        status += "\n**在建领域：**" + current["active_work"] + "\n"
    history = (f"{current['historical_boundary']}没有改写历史原始报告、评分、runtime pins或消耗授权。"
               "历史文档中的current/main/NEXT_READY不再控制当前队列。\n")
    generated = '<!-- Generated by python -m scripts.render_hcl_status from docs/hcl_design_manifest.json. -->\n'
    output = {}
    output['README.md'] = generated + '# Human Cognition Layer\n\n' + (
        '固定目标：必经调用、基础模型可替换，完成心理、复杂逻辑、行为、动机、情感、关系、'
        '文学、长程理解、哲学、伦理、概念、价值与复杂判断，实质增强强基础模型。\n\n'
        '用户已批准全系统整改v1.0、D1–D6推荐默认及后续连续实施。' + links + '\n\n'
        + status + '\n[当前状态](STATUS.md)与[执行计划入口](DEVELOPMENT_PLAN.md)由同一manifest生成。'
        '本次模型调用数为0，未新增收费、部署或sealed访问权限。\n\n' + history + '\n'
        '[原始README](docs/history/pre-redesign-20261012/README.md)；'
        '[历史目录](docs/history/pre-redesign-20261012/INDEX.md)。\n')
    output['STATUS.md'] = generated + '# HCL 当前状态\n\n' + links + '\n\n' + (
        f"实施基线main：`{current['base_main']}`。\n\n" + status + '\n'
        'S1尚未完整完成。真实本地算子与模拟端口的离线接通不能证明真实模型语义能力。'
        '每次运行的精确commit和代码文件hash由对应scripts/witness_unified_s*.py生成；'
        'CI在准确PR head上执行，不将旧回归数量作为新能力完成率。\n\n'
        f"本轮provider_calls={current['provider_calls']}；provider_spend_usd={current['provider_spend_usd']}；"
        f"sealed_content_reads={current['sealed_content_reads']}。\n\n" + history + '\n'
        '#323–#325仍未整包合并或关闭，SID001不重启。'
        '[历史状态](docs/history/pre-redesign-20261012/STATUS.md)。\n')
    output['DEVELOPMENT_PLAN.md'] = generated + '# HCL 当前正式执行计划入口\n\n' + links + '\n\n' + (
        '完整依赖：**S1 → S2 → {S3 ∥ S4} → S5 → S6 → S7**。'
        '全部M01–M16、P01–P38、T01–T32与61个迁移条目保持原范围，D1–D6按已批准默认执行。\n\n'
        + status + '\n'
        'S1.1首条闭环不是完整目标的替代品；内存store不是S1持久化完成证据。'
        '后续按既定切片继续，不新增竞争计划，也不等待收费授权才推进允许的离线工作。\n\n'
        + history + '\n[历史执行计划](docs/history/pre-redesign-20261012/DEVELOPMENT_PLAN.md)。\n')
    output['HCL_LONG_HORIZON_CAPABILITY_MASTER_PLAN.md'] = generated + (
        '# HCL Long-Horizon Capability Master Plan — 历史索引\n\n'
        '原A–H 41包Master Plan全文、目标与门槛已逐字保留于'
        '[历史Master Plan](docs/history/pre-redesign-20261012/HCL_LONG_HORIZON_CAPABILITY_MASTER_PLAN.md)，'
        '原始Git blob为`25fc771a3da04b3aced8cd1d20cdd2ec2a3f2df8`。\n\n' + history + '\n'
        + links + '\n\n' + status)
    return output


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest = json.loads((ROOT/'docs/hcl_design_manifest.json').read_text())
    for name, content in render(manifest).items():
        path = ROOT/name
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Generated plan index is stale: {name}')
        else:
            path.write_text(content)
